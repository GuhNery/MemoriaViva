-- Memória Viva — schema inicial compatível com a API atual (ambiente de desenvolvimento)
-- Banco: memoria_viva_dev, projeto Neon do usuário. Sem DROP/TRUNCATE/DELETE.
-- Observação: regras de negócio e modelo de mídia/comentários serão revisados depois.

CREATE TABLE IF NOT EXISTS usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL,
  senha TEXT NOT NULL,
  foto_perfil TEXT,
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS usuario_email_lower_uidx ON usuario (LOWER(email));

CREATE TABLE IF NOT EXISTS grupo (
  id_grupo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  descricao TEXT,
  foto_grupo TEXT,
  id_admin BIGINT NOT NULL REFERENCES usuario(id_usuario),
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS participante_grupo (
  id_participante_grupo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_grupo BIGINT NOT NULL REFERENCES grupo(id_grupo) ON DELETE CASCADE,
  permissao VARCHAR(16) NOT NULL DEFAULT 'member'
    CHECK (permissao IN ('admin', 'editor', 'member')),
  data_entrada TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id_usuario, id_grupo)
);

CREATE TABLE IF NOT EXISTS convite_grupo (
  id_convite BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo BIGINT NOT NULL REFERENCES grupo(id_grupo) ON DELETE CASCADE,
  id_convidante BIGINT NOT NULL REFERENCES usuario(id_usuario),
  email VARCHAR(150) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'accepted', 'cancelled')),
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (email, id_grupo)
);

CREATE TABLE IF NOT EXISTS subgrupo (
  id_subgrupo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_grupo BIGINT NOT NULL REFERENCES grupo(id_grupo) ON DELETE CASCADE,
  id_criador BIGINT NOT NULL REFERENCES usuario(id_usuario),
  nome VARCHAR(150) NOT NULL,
  descricao TEXT,
  data_evento DATE,
  visibilidade VARCHAR(16) NOT NULL DEFAULT 'family'
    CHECK (visibilidade IN ('family','private')),
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS participante_subgrupo (
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario) ON DELETE CASCADE,
  id_subgrupo BIGINT NOT NULL REFERENCES subgrupo(id_subgrupo) ON DELETE CASCADE,
  permissao VARCHAR(16) NOT NULL DEFAULT 'member'
    CHECK (permissao IN ('admin','editor','member')),
  PRIMARY KEY (id_usuario, id_subgrupo)
);

CREATE TABLE IF NOT EXISTS midia (
  id_midia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_subgrupo BIGINT NOT NULL REFERENCES subgrupo(id_subgrupo) ON DELETE CASCADE,
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
  arquivo TEXT NOT NULL,
  descricao TEXT,
  tipo_midia VARCHAR(16) NOT NULL
    CHECK (tipo_midia IN ('image','video','audio','file')),
  data_upload TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  data_lembranca DATE -- preparado para cronologia pela data da lembrança
);

CREATE TABLE IF NOT EXISTS comentario (
  id_comentario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL REFERENCES usuario(id_usuario),
  id_subgrupo BIGINT REFERENCES subgrupo(id_subgrupo) ON DELETE CASCADE,
  id_midia BIGINT REFERENCES midia(id_midia) ON DELETE CASCADE,
  conteudo TEXT NOT NULL,
  data_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT comentario_um_destino_ck
    CHECK ((id_subgrupo IS NOT NULL) <> (id_midia IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS participante_grupo_grupo_idx ON participante_grupo(id_grupo);
CREATE INDEX IF NOT EXISTS subgrupo_grupo_idx ON subgrupo(id_grupo);
CREATE INDEX IF NOT EXISTS midia_subgrupo_idx ON midia(id_subgrupo);
CREATE INDEX IF NOT EXISTS comentario_subgrupo_idx ON comentario(id_subgrupo);
CREATE INDEX IF NOT EXISTS comentario_midia_idx ON comentario(id_midia);
